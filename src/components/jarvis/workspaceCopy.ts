export function workspaceCopy(language: Language) {
  const column =
    language === "dari" || language === "persian"
      ? 0
      : language === "pashto"
        ? 1
        : language === "arabic"
          ? 2
          : -1;
  if (column === -1) return (source: string) => source;
  return (source: string) => strings[source]?.[column] || source;
}
