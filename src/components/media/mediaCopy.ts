export function mediaCopy(language: Language): Copy {
  return language === "dari"
    ? fa
    : language === "persian"
      ? { ...fa, run: "اجرای کار", history: "تاریخچه کارها" }
      : language === "pashto"
        ? ps
        : language === "arabic"
          ? ar
          : en;
}
